#!/usr/bin/env node
/**
 * Generate every role's native agent definition from its installed `role.json`.
 *
 * A role is a skill; some agent kinds can also address a role by a native agent
 * name (Claude `.claude/agents/<name>.md`, Codex `.codex/agents/<name>.toml`,
 * Pi `.pi/agent/agents/<name>.md`). Those definitions used to be static templates
 * copied by setup-meerkat; they are now derived from the same `role.json` the
 * supervisor reads, so a role edit cannot leave a stale definition behind.
 *
 * Written files carry a marker line. A file without the marker is somebody
 * else's: it is reported and left alone unless `--force` says to replace it.
 *
 * Usage:
 *   node scripts/install/lib/native-agents.mjs --kind claude --home <dir>
 *     [--roles jobs,linus] [--dry-run] [--force]
 *
 * `--roles` limits the write to the roles a kind actually carries (omitted = every role
 * in the repository; an empty value = none). A generated definition left behind for a
 * role the kind no longer carries is reported as `stale` and never deleted.
 *
 * Node builtins only.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { isEntryPoint } from "../../../src/foundation/entry-guard.mjs";
import { nativeAgentToolLines } from "../../../src/foundation/role-tools.mjs";

const ROLE_SCHEMA = "meerkat-role";
const MARKER = "generated by meerkat-taskpanel install from role.json";

/** Where each kind keeps a native definition, relative to the target home. */
const NATIVE = Object.freeze({
  claude: { dir: ".claude/agents", ext: "md" },
  codex: { dir: ".codex/agents", ext: "toml" },
  pi: { dir: ".pi/agent/agents", ext: "md" },
});

const USAGE = `Usage: node scripts/install/lib/native-agents.mjs --kind <claude|codex|pi> --home <dir> [--roles <list>] [--dry-run] [--force]`;

/** `--roles` values are comma- or whitespace-separated; null means every role. */
function selectedRoles(raw) {
  if (raw === null) return null;
  return [...new Set(String(raw).split(/[\s,]+/).filter(Boolean))];
}

function parse(argv) {
  const opts = { kind: null, home: process.env.HOME ?? null, roles: null, dryRun: false, force: false, help: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    const take = () => {
      const value = argv[++i];
      if (value === undefined) throw new Error(`${arg} requires a value`);
      return value;
    };
    switch (arg) {
      case "--kind": opts.kind = take(); break;
      case "--home": opts.home = resolve(take()); break;
      case "--roles": opts.roles = take(); break;
      case "--dry-run": opts.dryRun = true; break;
      case "--force": opts.force = true; break;
      case "-h":
      case "--help": opts.help = true; break;
      default:
        if (arg.startsWith("--roles=")) opts.roles = arg.slice("--roles=".length);
        else throw new Error(`unknown option: ${arg}`);
    }
  }
  return opts;
}

/** One line, never a newline: a description sits inside frontmatter/TOML. */
const oneLine = (text) => String(text ?? "").replace(/\s+/g, " ").trim();

/**
 * The lane a role renders as: a worker that also reviews keeps the wider
 * surface; a director lane exists in the table for kinds an installer may add
 * later, and a review-only role is a reviewer.
 */
function roleLane(role) {
  if (role.lanes.includes("worker")) return "worker";
  if (role.lanes.includes("director")) return "director";
  return "reviewer";
}

/** Claude / Pi markdown: YAML frontmatter plus the role's working pointers. */
function markdownDefinition(role, kind) {
  // One table for the adapters and the installer (`src/foundation/role-tools.mjs`):
  // a native definition must not grant a surface the session itself would refuse.
  // A full lane adds no tool line at all — omitting `tools` is what makes both
  // kinds inherit their whole pool. The reviewer carries a deny line instead.
  const toolLines = nativeAgentToolLines(roleLane(role), kind);
  return [
    "---",
    `name: ${role.native_agent}`,
    `description: ${oneLine(role.description)}`,
    ...toolLines,
    "---",
    "",
    `<!-- ${MARKER} (${role.id}) -->`,
    "",
    `You are **${role.agent}**. Your workflow is the installed \`${role.id}\` skill: read`,
    `\`<agent-dir>/skills/${role.id}/SKILL.md\` and its \`references/\` before acting, and follow`,
    "the handoff you were given verbatim.",
    "",
    role.summary ? `${role.summary}` : "",
    "",
    "Board operations are the `meerkat` skill's contract; decisions are the",
    "`meerkat-director` skill's. Never move a card to `done` yourself.",
    "",
  ].join("\n");
}

/** Codex TOML definition. */
function tomlDefinition(role) {
  return [
    `# ${MARKER} (${role.id})`,
    `name = ${JSON.stringify(role.native_agent)}`,
    `description = ${JSON.stringify(oneLine(role.description))}`,
    `developer_instructions = ${JSON.stringify(
      `You are ${role.agent}. Your workflow is the installed ${role.id} skill: read <agent-dir>/skills/${role.id}/SKILL.md and its references/ before acting, and follow the handoff verbatim. Board operations are the meerkat skill's contract; decisions are the meerkat-director skill's. Never move a card to done yourself.`,
    )}`,
    "",
  ].join("\n");
}

/**
 * The role.json fields a caller needs, or `null` when the directory is not a
 * role. Exported so the installer's role lister and this generator read the same
 * marker (`scripts/install/lib/role-skills.mjs`).
 *
 * @param {string} dir a skill directory
 * @returns {{id: string, agent: string, native_agent: string, description: string, summary: string, lanes: string[]}|null}
 */
export function readRoleSkill(dir) {
  const path = join(dir, "role.json");
  if (!existsSync(path)) return null;
  let raw;
  try {
    raw = JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
  if (raw?.schema !== ROLE_SCHEMA) return null;
  const lanes = Array.isArray(raw.lanes) && raw.lanes.length > 0 ? raw.lanes : ["worker"];
  return {
    id: String(raw.id ?? "").trim(),
    agent: String(raw.agent ?? raw.id ?? "").trim(),
    native_agent: String(raw.native_agent ?? raw.id ?? "").trim(),
    description: raw.description ?? raw.summary ?? String(raw.title ?? raw.agent ?? ""),
    summary: oneLine(raw.summary ?? ""),
    lanes,
  };
}

/** @returns {{written: string[], unchanged: string[], skipped: string[], conflicts: string[], stale: string[]}} */
export function writeNativeAgents({ kind, home, repo, roles = null, dryRun = false, force = false }) {
  const result = { written: [], unchanged: [], skipped: [], conflicts: [], stale: [] };
  const target = NATIVE[kind];
  if (target === undefined) {
    result.skipped.push(`${kind} has no native agent format`);
    return result;
  }
  const skillsDir = join(repo, "skills");
  if (!existsSync(skillsDir)) {
    result.conflicts.push(`role skills not found at ${skillsDir}`);
    return result;
  }
  const selected = roles === null ? null : new Set(roles);
  const outDir = join(home, target.dir);
  for (const name of readdirSync(skillsDir, { withFileTypes: true })) {
    if (!name.isDirectory()) continue;
    const role = readRoleSkill(join(skillsDir, name.name));
    if (role === null || role.id === "" || role.native_agent === "") continue;
    const dest = join(outDir, `${role.native_agent}.${target.ext}`);
    // A role this kind does not carry: never write it, but report a generated
    // definition left behind by an earlier install or a role move.
    if (selected !== null && !selected.has(name.name) && !selected.has(role.id)) {
      if (existsSync(dest) && readFileSync(dest, "utf8").includes(MARKER)) result.stale.push(dest);
      continue;
    }
    const body = kind === "codex" ? tomlDefinition(role) : markdownDefinition(role, kind);
    if (existsSync(dest)) {
      const current = readFileSync(dest, "utf8");
      if (current === body) {
        result.unchanged.push(dest);
        continue;
      }
      if (!current.includes(MARKER) && !force) {
        result.conflicts.push(dest);
        continue;
      }
    }
    if (!dryRun) {
      mkdirSync(outDir, { recursive: true });
      writeFileSync(dest, body, "utf8");
    }
    result.written.push(dest);
  }
  return result;
}

function main(argv) {
  const opts = parse(argv);
  if (opts.help) {
    console.log(USAGE);
    return 0;
  }
  if (!(opts.kind in NATIVE)) {
    console.error(`native-agents: unknown or unsupported kind ${JSON.stringify(opts.kind)}`);
    return 2;
  }
  if (typeof opts.home !== "string" || opts.home === "") {
    console.error("native-agents: --home is required");
    return 2;
  }
  const repo = resolve(fileURLToPath(new URL("../../..", import.meta.url)));
  const result = writeNativeAgents({
    kind: opts.kind,
    home: opts.home,
    repo,
    roles: selectedRoles(opts.roles),
    dryRun: opts.dryRun,
    force: opts.force,
  });
  for (const path of result.written) console.log(`${opts.dryRun ? "would write" : "wrote"} ${path}`);
  for (const path of result.unchanged) console.log(`unchanged ${path}`);
  for (const path of result.stale) {
    console.log(`stale ${path} (role not carried on ${opts.kind}; left in place — /setup-meerkat can move it)`);
  }
  for (const path of result.conflicts) {
    console.error(`conflict ${path}: a file without the generated marker; re-run with --force to replace it`);
  }
  for (const line of result.skipped) console.log(`skip ${line}`);
  return result.conflicts.length > 0 ? 1 : 0;
}

if (isEntryPoint(import.meta.url)) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (err) {
    console.error(`native-agents: ${err instanceof Error ? err.message : String(err)}`);
    process.exit(2);
  }
}
