-- 0014_task_source_index.sql — restore the index 0013's rebuild dropped.
--
-- ---------------------------------------------------------------------------
-- What went wrong
-- ---------------------------------------------------------------------------
--
-- 0013 widens `tasks.status` the only way SQLite allows — create-new / copy /
-- drop-old / rename-new — and `DROP TABLE tasks` takes the table's indexes with
-- it, so the file re-creates them by hand. That list is short by one: it names
-- six (`ux_tasks_identifier`, `ux_tasks_source`, `ix_tasks_board`,
-- `ix_tasks_assignee`, `ix_tasks_heartbeat`, `ux_tasks_idem_active`) while the
-- history it claims to restore — 0001 + 0005 + 0009 — defines **seven** indexes
-- on `tasks`. The one left out is 0005's:
--
--   CREATE INDEX IF NOT EXISTS ix_tasks_source ON tasks(project_id, source_path)
--     WHERE source_path IS NOT NULL;         -- 0005_task_meta.sql:25, verbatim
--
-- Nothing fails when it is missing. A board that has run 0013 and a board built
-- from scratch claim the same migration set and then carry *different* physical
-- schemas, which is the defect this file closes: an upgrade and a fresh install
-- must land on the same index set.
--
-- The loss cannot be repaired in place. `schema_migrations` records each file's
-- SHA-256 and the runner refuses a database whose applied file changed
-- (`MIGRATION_CHECKSUM_MISMATCH`); `scripts/verify/migrations.mjs` refuses the
-- same edit one step earlier, in the pre-commit hook. So 0013's text stays
-- exactly as shipped, and the index comes back here.
--
-- ---------------------------------------------------------------------------
-- The erratum 0013 carries (its text is frozen, so the correction lives here)
-- ---------------------------------------------------------------------------
--
-- Three sentences in 0013 describe the index set it re-created, and each is
-- wrong about the count or the provenance:
--
--   * 0013:30  "the table's own 6 indexes are re-created (they go with the old
--     table)" — the file re-creates 6, but the table's own is 7;
--   * 0013:78  "are re-created below: the 6 indexes verbatim" — same count;
--   * 0013:215 "Indexes (0001 + 0005 + 0009, verbatim names and shapes)" — the
--     provenance is right and the arithmetic is not: those three files create 7
--     indexes, and the section the heading introduces creates 6. It names 0005
--     while omitting the one index 0005 added.
--
-- The whole set, with the one 0013 lost marked:
--
--   ux_tasks_identifier  0001  UNIQUE (project_id, identifier)
--   ux_tasks_source      0001  UNIQUE (project_id, source_path) WHERE source_path IS NOT NULL
--   ix_tasks_board       0001  (project_id, status, sort_order)
--   ix_tasks_assignee    0001  (project_id, assignee_id)
--   ix_tasks_heartbeat   0001  (status, heartbeat_at)
--   ix_tasks_source      0005  (project_id, source_path) WHERE source_path IS NOT NULL   <- lost by 0013
--   ux_tasks_idem_active 0009  UNIQUE (idem) WHERE idem IS NOT NULL AND status NOT IN ('done','canceled')
--
-- One thing worth recording for whoever reads this next: 0005's index is
-- **redundant** today — it is the same columns and the same partial predicate as
-- 0001's `ux_tasks_source`, and the importer's per-card lookup
-- (`md/import.mjs#findExisting`) lists the project's rows and filters in JS
-- rather than querying by `source_path`. So restoring it buys parity with a fresh
-- board, not speed. Whether the duplicate should exist at all is a separate
-- decision that this file does not make: 0013's rebuild stated job was to
-- preserve everything, and this restores what 0005 actually shipped.
--
-- ---------------------------------------------------------------------------
-- The statement
-- ---------------------------------------------------------------------------
--
-- 0005's line, verbatim — same name, same columns, same predicate, same
-- `IF NOT EXISTS`.
--
--   * `CREATE … IF NOT EXISTS` rather than 0013's `DROP … IF EXISTS` + `CREATE`:
--     this file adds one index to a table it does not rebuild, so there is no
--     renamed-table trap to disarm. The guard only makes it harmless on a board
--     that somehow still has the index.
--   * `WHERE source_path IS NOT NULL` is not decoration. It is the shape 0005
--     shipped, and parity is a claim about the index set, not about names — an
--     index restored under the right name with the wrong predicate is a
--     different index wearing the same label.
--   * no `-- @foreign-keys: off` marker: nothing here drops or rebuilds a table,
--     so foreign key enforcement is untouched.
--
-- `test/core/storage/migrations-0013.test.mjs` keeps this from happening again:
-- it derives the index set from a board built **before** 0013 and asserts the
-- upgrade returns exactly that set — and that a fresh board has it too — so the
-- next rebuild that loses an index fails a test instead of shipping.
--
-- Append-only: 0001, 0005, 0009 and 0013 are never edited.

CREATE INDEX IF NOT EXISTS ix_tasks_source ON tasks(project_id, source_path) WHERE source_path IS NOT NULL;
