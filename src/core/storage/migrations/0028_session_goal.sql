-- 0028_session_goal.sql — an agent session records the sentence it is for.
--
-- ---------------------------------------------------------------------------
-- Why the session row
-- ---------------------------------------------------------------------------
--
-- The natural key is `(task_id, seg, owner)` (`0001`), which is what the board
-- calls a session: the discriminator plus the conversation that holds it. The
-- question "what is this segment working on?" belongs to that row, not to the
-- card — several segments run concurrently, and a card-level note cannot say
-- which one is doing what. The reports already carry `seg` for the same reason;
-- this is the one sentence a resumed conversation needs before it reads a
-- report.
--
-- ---------------------------------------------------------------------------
-- Why NOT NULL DEFAULT ''
-- ---------------------------------------------------------------------------
--
-- A pre-0028 row has no goal, and "no goal" is a complete answer — the drawer
-- simply renders no sentence. `''` keeps that state distinct from NULL (which
-- would make every reader branch on two spellings of absent), and the constant
-- default is what makes `ALTER TABLE ... ADD COLUMN` legal on a STRICT table
-- without rebuilding it. Nothing is back-filled: a session's goal is what it
-- said it was, never something this migration invented.

ALTER TABLE agent_sessions ADD COLUMN goal TEXT NOT NULL DEFAULT '';
